import time
import random

# Climas disponibles según la hora del día
CLIMAS_DIA = ["Soleado", "Soleado", "Soleado", "Lluvia", "Lluvia", "Tormenta"]
CLIMAS_NOCHE = ["Templado", "Templado", "Templado", "Lluvia", "Lluvia", "Tormenta"]
es_dia = True  # Variable global para rastrear si es día o noche

def obtener_clima():
    if es_dia:
        return random.choice(CLIMAS_DIA)
    else:
        return random.choice(CLIMAS_NOCHE)

def ciclo():
    global es_dia
    if es_dia == True:
        es_dia = False
    else:
        es_dia = True

    clima=obtener_clima()
    visibilidad=True

    if es_dia==False or clima=="Tormenta":
        visibilidad=False

    if  es_dia == True:
        if clima=="Soleado":
            return 0, visibilidad
        elif clima=="Lluvia":
            return 1, visibilidad
        else:
            return 2, visibilidad
    else:
        if clima=="Templado":
            return 3, visibilidad
        elif clima=="Lluvia":
            return 4, visibilidad
        else:
            return 5, visibilidad

if  __name__ == "__main__":
  print(f"El clima es: {obtener_clima()}")